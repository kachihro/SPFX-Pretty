import * as path from 'path';
import { ScanResult } from './types';

const EFFORT = { S: 'Small', M: 'Medium', L: 'Large' } as const;

function today(): string {
  const d = new Date();
  return `${String(d.getDate()).padStart(2, '0')}/${String(d.getMonth() + 1).padStart(2, '0')}/${d.getFullYear()}`;
}

/** Markdown upgrade assessment - ready to paste into a DevOps PBI or wiki. */
export function upgradeMarkdown(results: ScanResult[]): string {
  const lines: string[] = [`# SPFx version & upgrade assessment`, '', `_Generated by SPFX Pretty on ${today()}_`, ''];
  if (results.length > 1) {
    lines.push('| Solution | SPFx | Toolchain | Latest | Effort |', '|---|---|---|---|---|');
    for (const r of results) {
      const u = r.upgrade;
      lines.push(`| ${r.solution?.name ?? path.basename(r.root)} | ${u?.current ?? '?'} | ${u?.toolchain ?? '?'} | ${u?.latest ?? '?'} | ${u?.effort ?? '-'} |`);
    }
    lines.push('');
  }
  for (const r of results) {
    const u = r.upgrade;
    lines.push(`## ${r.solution?.name ?? path.basename(r.root)}`, '');
    if (!u) { lines.push('No SPFx version found in package.json.', ''); continue; }
    lines.push(
      `- **Current:** SPFx ${u.current} (${u.toolchain === 'gulp' ? 'gulp toolchain - legacy' : 'Heft toolchain'})`,
      `- **Latest:** SPFx ${u.latest}${u.hops.length ? ` - ${u.hops.length} release${u.hops.length === 1 ? '' : 's'} behind (${u.hops.join(', ')})` : ' - up to date'}`,
      `- **Overall effort:** ${u.effort}`,
      '',
      '| | Project | Target |', '|---|---|---|',
      `| React | ${u.compat.react.current ?? '-'} | ${u.compat.react.target ?? '-'} |`,
      `| Node | ${u.compat.node.current.map(n => 'v' + n).join(', ') || '-'} | ${u.compat.node.target.map(n => 'v' + n).join(', ') || '-'} |`,
      `| TypeScript | ${u.compat.typescript.current ?? '-'} | ${u.compat.typescript.target ?? '-'} |`,
      '',
    );
    const issues = r.findings.filter(f => f.category === 'Versions' && f.severity !== 'pass');
    if (issues.length) {
      lines.push('### Version issues now', '');
      for (const f of issues) { lines.push(`- **${f.severity === 'error' ? 'Error' : f.severity === 'warning' ? 'Warning' : 'Info'}** (${f.ruleId}): ${f.message}`); }
      lines.push('');
    }
    if (u.steps.length) {
      lines.push('### Upgrade steps', '');
      u.steps.forEach((s, i) => {
        lines.push(`${i + 1}. **${s.title}** - effort: ${EFFORT[s.effort]}`, `   ${s.detail}${s.link ? ` ([docs](${s.link}))` : ''}`);
      });
      lines.push('', 'Detailed file-by-file changes (CLI for Microsoft 365, run in the project folder):', '', '```powershell', u.command, '```', '');
    }
  }
  lines.push('Effort guide: Small = a few hours, Medium = about a day, Large = several days including testing. Adjust for your team.', '');
  return lines.join('\n');
}
